package com.achulkov.evokammer.cli.selfimprovement

import com.achulkov.evokammer.agents.factory.OverseerAgentRunner
import com.achulkov.evokammer.api.service.OverseerKernelService
import com.achulkov.evokammer.substrate.SubstrateDatabaseFactory
import io.github.aakira.napier.DebugAntilog
import io.github.aakira.napier.Napier
import kotlinx.coroutines.runBlocking
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import java.nio.file.Files
import java.nio.file.Path

private val loopJson = Json { prettyPrint = true; encodeDefaults = true }

/**
 * CLI-compatible runner for the recursive self-improvement loop.
 *
 * This is a thin integration layer that wires together the deterministic kernel,
 * the OverseerAgent (LLM proposer), and the run orchestrator into a single
 * command-line entry point.
 *
 * Each cycle:
 * 1. The OverseerAgent scans the current kernel state and proposes new hypotheses.
 * 2. Proposed hypotheses are formalized through the kernel (validated against immutable paths).
 * 3. Experiment plans are registered and scheduled.
 * 4. The orchestrator launches experiment runs and evaluates results.
 * 5. Results are fed back into the kernel, updating hypothesis status.
 *
 * @param workspaceRoot Output root for the loop's persistent state and run data.
 * @param openRouterApiKey API key for LLM calls.
 */
class SelfImprovementLoopRunner(
    private val workspaceRoot: Path,
    private val openRouterApiKey: String
) {
    /**
     * Structured report for a single loop cycle.
     *
     * @param cycleIndex Zero-based cycle index.
     * @param hypothesesCount Total hypotheses after the cycle.
     * @param proposalsCount Number of new proposals generated by the OverseerAgent.
     * @param formalizedCount Number of proposals successfully formalized by the kernel.
     * @param experimentResults Results recorded in this cycle.
     * @param errors Non-fatal errors encountered.
     */
    @Serializable
    data class CycleReport(
        val cycleIndex: Int,
        val hypothesesCount: Int,
        val proposalsCount: Int,
        val formalizedCount: Int,
        val experimentResults: Int,
        val errors: List<String> = emptyList()
    )

    private val substrateFactory: SubstrateDatabaseFactory by lazy {
        SubstrateDatabaseFactory(workspaceRoot.resolve(".evokammer-data").toFile())
    }

    private val kernelService: OverseerKernelService by lazy {
        OverseerKernelService(
            substrateFactory = substrateFactory
        )
    }

    private val agentRunner: OverseerAgentRunner by lazy {
        OverseerAgentRunner(openRouterApiKey = openRouterApiKey)
    }

    /**
     * Runs the self-improvement loop for up to [cycleLimit] cycles.
     *
     * @param cycleLimit Maximum number of cycles to run.
     * @return List of cycle reports.
     */
    fun runCycle(cycleLimit: Int = 3): List<CycleReport> {
        Napier.base(DebugAntilog())
        Napier.i("SelfImprovementLoopRunner: starting loop (max $cycleLimit cycles)")
        Files.createDirectories(workspaceRoot)

        val reports = mutableListOf<CycleReport>()

        runBlocking {
            for (cycle in 0 until cycleLimit) {
                Napier.i("SelfImprovementLoopRunner: cycle ${cycle + 1}/$cycleLimit")

                val report = runCatching {
                    runSingleCycle(cycle)
                }.getOrElse { e ->
                    Napier.e("SelfImprovementLoopRunner: cycle $cycle failed", e)
                    CycleReport(
                        cycleIndex = cycle,
                        hypothesesCount = kernelService.currentState().hypotheses.size,
                        proposalsCount = 0,
                        formalizedCount = 0,
                        experimentResults = 0,
                        errors = listOf("Cycle failed: ${e.message}")
                    )
                }

                reports += report

                // Stop early if no progress was made
                if (report.proposalsCount == 0 && report.experimentResults == 0) {
                    Napier.i("SelfImprovementLoopRunner: no progress in cycle $cycle, stopping.")
                    break
                }
            }
        }

        Napier.i("SelfImprovementLoopRunner: loop complete — ${reports.size} cycles")
        return reports
    }

    private suspend fun runSingleCycle(cycleIndex: Int): CycleReport {
        val errors = mutableListOf<String>()
        val stateBefore = kernelService.currentState()

        // 1. OverseerAgent proposes new hypotheses
        var proposalsCount = 0
        var formalizedCount = 0

        runCatching {
            val proposal = agentRunner.propose(
                kernelState = stateBefore,
                metaArchiveSummary = ""
            )

            proposalsCount = proposal.proposedHypotheses.size + proposal.proposedExperimentPlans.size

            // 2. Formalize proposed hypotheses through the kernel
            for (hypothesis in proposal.proposedHypotheses) {
                runCatching {
                    val preflight = kernelService.preflightHypothesis(hypothesis)
                    if (preflight.allowed) {
                        kernelService.formalizeHypothesis(hypothesis)
                        formalizedCount++
                        Napier.i("SelfImprovementLoopRunner: formalized hypothesis '${hypothesis.id}'")
                    } else {
                        errors += "Hypothesis '${hypothesis.id}' rejected by kernel: ${preflight.reasons.joinToString("; ")}"
                        Napier.w("SelfImprovementLoopRunner: hypothesis '${hypothesis.id}' rejected: ${preflight.reasons}")
                    }
                }.onFailure { e ->
                    errors += "Failed to formalize hypothesis '${hypothesis.id}': ${e.message}"
                    Napier.e("SelfImprovementLoopRunner: failed to formalize '${hypothesis.id}'", e)
                }
            }

            // 3. Register proposed experiment plans
            for (plan in proposal.proposedExperimentPlans) {
                runCatching {
                    val preflight = kernelService.preflightExperimentPlan(plan)
                    if (preflight.allowed) {
                        kernelService.registerExperimentPlan(plan)
                        Napier.i("SelfImprovementLoopRunner: registered experiment plan '${plan.id}'")
                    } else {
                        errors += "Experiment plan '${plan.id}' rejected by kernel: ${preflight.reasons.joinToString("; ")}"
                        Napier.w("SelfImprovementLoopRunner: plan '${plan.id}' rejected: ${preflight.reasons}")
                    }
                }.onFailure { e ->
                    errors += "Failed to register experiment plan '${plan.id}': ${e.message}"
                    Napier.e("SelfImprovementLoopRunner: failed to register plan '${plan.id}'", e)
                }
            }
        }.onFailure { e ->
            errors += "OverseerAgent proposal failed: ${e.message}"
            Napier.e("SelfImprovementLoopRunner: proposal failed", e)
        }

        // 4. Schedule and run experiments (if kernel state and run service are available)
        var experimentResults = 0

        // The orchestrator requires a full EvoKammerRunService which needs the runtime.
        // For MVP, we record that scheduling happened without live execution.
        runCatching {
            val scheduled = kernelService.scheduleEligibleExperimentPlansWithAudit()
            val newlyScheduled = scheduled.state.experimentSchedules.values.count { it.launchedAtMs == null }
            if (newlyScheduled > 0) {
                Napier.i("SelfImprovementLoopRunner: $newlyScheduled experiment plans scheduled (awaiting launch)")
            }
        }.onFailure { e ->
            errors += "Scheduling failed: ${e.message}"
        }

        val stateAfter = kernelService.currentState()

        return CycleReport(
            cycleIndex = cycleIndex,
            hypothesesCount = stateAfter.hypotheses.size,
            proposalsCount = proposalsCount,
            formalizedCount = formalizedCount,
            experimentResults = experimentResults,
            errors = errors
        )
    }
}
