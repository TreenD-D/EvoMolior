package com.achulkov.evomolior.agents.factory

import com.achulkov.evomolior.core.config.ModelSelectionConfig
import com.achulkov.evomolior.core.config.LlmBackend
import com.achulkov.evomolior.core.contract.CriticReview
import com.achulkov.evomolior.substrate.db.entity.StagingSubmissionEntity

/**
 * Specialized critic wrapper for KG fact arbitration.
 *
 * When the KG consistency checker flags a conflict, this wrapper gives the critic a narrower
 * arbitration prompt focused on the conflicting facts and the reason the fact was disputed.
 * It keeps the generic critic path untouched while making KG conflict review explicit.
 *
 * @param openRouterApiKey API key for the selected [llmBackend].
 * @param llmBackend Backend used for arbitration model resolution and prompt execution.
 * @param criticModelId Model identifier used for arbitration.
 * @param deterministicReviewRunner Optional injected runner for tests and offline runtimes.
 */
class KgCriticArbitrationAgent(
    openRouterApiKey: String,
    llmBackend: LlmBackend = LlmBackend.OPENROUTER,
    criticModelId: String = ModelSelectionConfig.DEFAULT_CRITIC_PIPELINE_MODEL,
    deterministicReviewRunner: (suspend (
        submission: StagingSubmissionEntity,
        prompt: String,
        disputeContext: String?,
        criticId: String
    ) -> CriticReview)? = null,
    providerCostRecorder: ((String) -> ProviderCallCostRecorder)? = null
) {
    private val criticReviewAgent = CriticReviewAgent(
        openRouterApiKey = openRouterApiKey,
        llmBackend = llmBackend,
        criticModelId = criticModelId,
        systemPrompt = KG_ARBITRATION_SYSTEM_PROMPT,
        deterministicReviewRunner = deterministicReviewRunner,
        providerCostRecorder = providerCostRecorder
    )

    /**
     * Reviews a KG fact after the consistency checker has detected a conflict.
     *
     * @param submission The KG_FACT submission being arbitrated.
     * @param disputeContext The KG conflict details generated by the consistency checker.
     * @param criticId Stable critic identity for the arbitration pass.
     * @return The arbitration verdict.
     */
    suspend fun reviewConflict(
        submission: StagingSubmissionEntity,
        disputeContext: String,
        criticId: String
    ): CriticReview {
        val prompt = buildPrompt(submission, disputeContext)
        return criticReviewAgent.reviewPrompt(
            submission = submission,
            prompt = prompt,
            disputeContext = disputeContext,
            criticId = criticId
        )
    }

    private fun buildPrompt(submission: StagingSubmissionEntity, disputeContext: String): String = buildString {
        append("""
            Review this KG_FACT submission in KG-Critic arbitration.

            Submission ID: ${submission.id}
            Source role: ${submission.role}
            Speculative: ${submission.speculative}
            Outlier: ${submission.outlier}

            Proposed fact:
            ---
            ${submission.content.take(8000)}
            ${if (submission.content.length > 8000) "\n[...truncated...]" else ""}
            ---

            Conflict context:
            ---
            $disputeContext
            ---

            Respond with a JSON object containing:
            - "outcome": "PROMOTE", "REJECT", or "DISPUTE"
            - "initialTrustScore": number 0.0-1.0 (only if PROMOTE)
            - "reason": string (required if REJECT or DISPUTE, optional if PROMOTE)

            Criteria:
            - PROMOTE only if the proposed fact is better supported than the conflicting fact(s)
            - REJECT if the new fact is still contradicted by higher-trust evidence
            - DISPUTE if the conflict remains ambiguous after reviewing the evidence

            JSON response only:
        """.trimIndent())
        append("\n\nNOTE — This is a SECOND REVIEW (KG arbitration). Your verdict is final.")
    }

    private companion object {
        val KG_ARBITRATION_SYSTEM_PROMPT = """
            You are the EvoMolior KG-Critic arbitration specialist.

            Your job is to resolve conflicts between a proposed KG fact and existing higher-trust
            facts. Be rigorous, evidence-based, and conservative.

            Prefer promotion only when the conflict is genuinely resolved. If uncertainty remains,
            reject or dispute rather than forcing an unsupported promotion.

            Always return a JSON object only.
        """.trimIndent()
    }
}
